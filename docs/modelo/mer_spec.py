"""Especificación única del modelo entidad-relación (MER) de Inventia, versión 1.2.0.

De esta especificación salen el MER, las reglas de negocio (Tabla K1), la matriz de verificación (Tabla K2) y las
relaciones con su cardinalidad (Tabla 48) que se publican en el documento del proyecto. La prueba automática
``backend/tests/test_mer_consistente.py`` la compara con las llaves foráneas reales de los modelos: si el código
cambia una llave, una restricción única o la obligatoriedad de una columna sin actualizar esta especificación (o al
revés), la prueba falla. Los cambios al MER se tramitan como solicitud de cambio (CRF), p. ej. CRF-MER-01.

Notación de la cardinalidad «A — B»: A es la participación del lado de la llave referenciada (la «madre») en la
relación y B la del lado de la tabla que lleva la llave. «1» = obligatoria (las columnas de la llave son NOT NULL);
«0..1» = opcional (alguna columna admite NULL); «N» = varias filas (la llave no es única); «1» en el lado B = la
llave es única (UNIQUE o PK). El mínimo «1..N» de una composición lo hace cumplir el servicio y no se verifica
contra la base. R05 es de muchos a muchos y se resuelve en ``rol_permisos`` (dos llaves foráneas).
"""

