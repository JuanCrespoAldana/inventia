def nivel(p, i):
    s = p * i
    return "Alto" if s >= 12 else "Medio" if s >= 6 else "Bajo"


def como_diccionarios():
    campos = ("id", "nombre", "p", "i", "mitigacion", "contingencia", "responsable", "estado", "evidencia")
    return [dict(zip(campos, r), puntaje=r[2] * r[3], nivel=nivel(r[2], r[3]), categoria=CATEGORIAS[r[0][:2]]) for r in RIESGOS]


